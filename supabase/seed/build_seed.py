"""Builds supabase/migrations/20261112000003_seed_draft_content.sql from content_draft.py.

Ids are deterministic (uuid5), so re-running the generated SQL never duplicates rows.
Usage: python3 supabase/seed/build_seed.py
"""
import json
import os
import sys
import uuid

sys.path.insert(0, os.path.dirname(__file__))
import content_draft as C  # noqa: E402

NS = uuid.UUID("6f1c2d5e-1212-4c12-9a12-121212121212")
OUT = os.path.join(os.path.dirname(__file__), "..", "migrations", "20261112000003_seed_draft_content.sql")


def uid(*parts):
    return str(uuid.uuid5(NS, "/".join(str(p) for p in parts)))


def s(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, (list, dict)):
        return "'" + json.dumps(v).replace("'", "''") + "'::jsonb"
    return "'" + str(v).replace("'", "''") + "'"


def arr(items):
    return "array[" + ",".join(s(i) for i in items) + "]::text[]" if items else "'{}'::text[]"


sql = [
    "-- GENERATED by supabase/seed/build_seed.py from content_draft.py. Do not edit by hand.",
    "-- DRAFT curriculum, rubric and personas for the demo. Every lesson is flagged is_draft_content = true.",
    "-- Paste into Supabase > SQL Editor and run once (safe to re-run: existing rows are skipped).",
    "",
]
emit = sql.append

# Skills
for i, (slug, name, stage, desc, good) in enumerate(C.SKILLS):
    emit(f"insert into public.skills (id, slug, name, stage, description, what_good_sounds_like, position) values "
         f"({s(uid('skill', slug))}, {s(slug)}, {s(name)}, {s(stage)}, {s(desc)}, {s(good)}, {i}) on conflict do nothing;")

# Personas
for p in C.PERSONAS:
    emit("insert into public.personas (id, slug, name, setting, difficulty, backstory, opening_line, objections, "
         "success_condition, start_trust, published) values "
         f"({s(uid('persona', p['slug']))}, {s(p['slug'])}, {s(p['name'])}, {s(p['setting'])}, {p['difficulty']}, "
         f"{s(p['backstory'])}, {s(p['opening_line'])}, {s(p['objections'])}, {s(p['success_condition'])}, "
         f"{p['start_trust']}, true) on conflict do nothing;")


def persona_id(slug):
    return uid("persona", slug)


def track(slug, name, rep_type, desc):
    emit("insert into public.tracks (id, slug, name, rep_type, description, total_days, published) values "
         f"({s(uid('track', slug))}, {s(slug)}, {s(name)}, {s(rep_type)}, {s(desc)}, 60, true) on conflict do nothing;")
    return uid("track", slug)


def quiz(key, title, kind, questions, pass_pct=80):
    qid = uid("quiz", key)
    emit(f"insert into public.quizzes (id, title, kind, pass_pct, published) values "
         f"({s(qid)}, {s(title)}, {s(kind)}, {pass_pct}, true) on conflict do nothing;")
    for i, qq in enumerate(questions, start=1):
        emit("insert into public.quiz_questions (id, quiz_id, position, prompt, qtype, options, correct, explanation, skill_slug) values "
             f"({s(uid('question', key, i))}, {s(qid)}, {i}, {s(qq['prompt'])}, {s(qq['qtype'])}, {s(qq['options'])}, "
             f"'{json.dumps(qq['correct'])}'::jsonb, {s(qq['explanation'])}, {s(qq['skill'])}) on conflict do nothing;")
    return qid


def week(track_slug, track_id, number, title, goal, assessment_id=None):
    wid = uid("week", track_slug, number)
    emit("insert into public.weeks (id, track_id, number, title, goal, assessment_quiz_id) values "
         f"({s(wid)}, {s(track_id)}, {number}, {s(title)}, {s(goal)}, {s(assessment_id)}) on conflict do nothing;")
    return wid


def day(track_slug, week_id, number, title):
    did = uid("day", track_slug, number)
    emit(f"insert into public.days (id, week_id, day_number, title) values ({s(did)}, {s(week_id)}, {number}, {s(title)}) on conflict do nothing;")
    return did


def lesson(key, title, summary, body, skills, module="core"):
    lid = uid("lesson", key)
    emit("insert into public.lessons (id, title, summary, body_md, module, skill_slugs, is_draft_content, published) values "
         f"({s(lid)}, {s(title)}, {s(summary)}, {s(body)}, {s(module)}, {arr(skills)}, true, true) on conflict do nothing;")
    return lid


def task(track_slug, day_number, pos, kind, title, ref=None, instructions=None, minutes=None, required=True):
    emit("insert into public.tasks (id, day_id, position, kind, ref_id, title, instructions, est_minutes, required) values "
         f"({s(uid('task', track_slug, day_number, pos))}, {s(uid('day', track_slug, day_number))}, {pos}, {s(kind)}, {s(ref)}, "
         f"{s(title)}, {s(instructions)}, {s(minutes)}, {s(required)}) on conflict do nothing;")


def reflection_instructions(prompts):
    return "\n".join(prompts)


# ── New Setter ──
NS_SLUG = "new-setter"
ns_track = track(NS_SLUG, "New Setter", "setter", "Your first 60 days, from zero to a consistent, appointment-setting setter.")
review_persona = {1: "busy-brenda", 2: "skeptic-steve"}

for wk in (C.WEEK1, C.WEEK2):
    n = wk["number"]
    a_id = quiz(f"{NS_SLUG}-week{n}-assessment", f"Week {n} assessment", "assessment", wk["assessment"])
    w_id = week(NS_SLUG, ns_track, n, wk["title"], wk["goal"], a_id)
    for d in wk["days"]:
        dn = d["day"]
        day(NS_SLUG, w_id, dn, d["title"])
        pos = 1
        if d.get("review"):
            task(NS_SLUG, dn, pos, "quiz", f"Week {n} assessment", a_id, "Pass with 80% or better to unlock next week.", 10); pos += 1
            task(NS_SLUG, dn, pos, "roleplay", f"Assessment role play: {review_persona[n].replace('-', ' ').title()}",
                 persona_id(review_persona[n]), "Run it until you score 70 or better.", 10); pos += 1
        else:
            L = d["lesson"]
            l_id = lesson(f"{NS_SLUG}-day{dn}", L["title"], L["summary"], L["body"], L["skills"], L.get("module", "core"))
            task(NS_SLUG, dn, pos, "lesson", L["title"], l_id, None, 8); pos += 1
            q_id = quiz(f"{NS_SLUG}-day{dn}", f"Day {dn} check", "quiz", d["quiz"], pass_pct=67)
            task(NS_SLUG, dn, pos, "quiz", f"Day {dn} check", q_id, "3 quick questions.", 3); pos += 1
            if d.get("roleplay"):
                p = d["roleplay"]
                task(NS_SLUG, dn, pos, "roleplay", f"Practice: {next(x['name'] for x in C.PERSONAS if x['slug'] == p)}",
                     persona_id(p), "Run at least one role play.", 10); pos += 1
        if d.get("reflection"):
            R = d["reflection"]
            task(NS_SLUG, dn, pos, "reflection", R["title"], None, reflection_instructions(R["prompts"]), 5); pos += 1
        if d.get("field"):
            F = d["field"]
            task(NS_SLUG, dn, pos, "field_task", F["title"], None, F["instructions"], 240); pos += 1

STUB_BODY = """**Draft outline.** Chase records this lesson on the studio day; until then, use it as a talking point with your trainer.

## What this lesson covers
- {title}: the core idea and why it matters
- What it sounds like on a real door
- Today's practice: try it on at least five doors and note what happened"""

for n, title, goal, day_titles in C.OUTLINE_WEEKS:
    w_id = week(NS_SLUG, ns_track, n, title, goal, None)
    start = (n - 1) * 7 + 1
    titles = day_titles + [f"Week {n} review" if n < 9 else "Graduation: 60 days done"]
    for i, t in enumerate(titles):
        dn = start + i
        if dn > 60:
            break
        day(NS_SLUG, w_id, dn, t)
        if i < len(day_titles):
            l_id = lesson(f"{NS_SLUG}-day{dn}", t, "Draft outline. Full lesson coming from Chase.", STUB_BODY.format(title=t), [])
            task(NS_SLUG, dn, 1, "lesson", t, l_id, None, 8)
            task(NS_SLUG, dn, 2, "field_task", "Knock 60 doors", None, "Knock 60 doors and log doors, conversations, bills and appointments.", 240)
        else:
            task(NS_SLUG, dn, 1, "reflection", f"Week {n} look back" if n < 9 else "60 days: look back",
                 None, "What improved most this week?\nWhat will you do differently next week?", 5)
            task(NS_SLUG, dn, 2, "field_task", "Knock 60 doors", None, "Knock 60 doors and log your numbers.", 240)

# ── Other tracks: week 1 structure ──
for t in C.OTHER_TRACKS:
    t_id = track(t["slug"], t["name"], t["rep_type"], t["description"])
    w_title, w_goal, titles = t["week1"]
    w_id = week(t["slug"], t_id, 1, w_title, w_goal, None)
    for i, title in enumerate(titles, start=1):
        day(t["slug"], w_id, i, title)
        if i < len(titles):
            l_id = lesson(f"{t['slug']}-day{i}", title, "Draft outline. Full lesson coming from Chase.", STUB_BODY.format(title=title), [])
            task(t["slug"], i, 1, "lesson", title, l_id, None, 8)
            if t["rep_type"] == "closer":
                task(t["slug"], i, 2, "roleplay", "Practice at the table", persona_id("tom-maria" if i % 2 else "numbers-nate"),
                     "Run at least one table role play.", 15)
            else:
                task(t["slug"], i, 2, "field_task", "Knock 60 doors", None, "Knock 60 doors and log your numbers.", 240)
        else:
            task(t["slug"], i, 1, "reflection", "Week 1 check-in", None, "What's working?\nWhat's the one thing to fix next week?", 5)

with open(OUT, "w") as f:
    f.write("\n".join(sql) + "\n")
print(f"wrote {OUT} ({len(sql)} lines)")
